/**
 * Builds `src/migrations/postgres/data/indonesia-kabkota-wilayah.generated.ts`
 * from emsifa/api-wilayah-indonesia static JSON, with Papua pemekaran mapping (UU 2022)
 * and Papua Barat / Papua Barat Daya split (Sorong Raya → prov. 96).
 *
 * Run from repo root: node be-samarta-easb-room/scripts/generate-indonesia-kabkota-seed.mjs
 */
import https from 'https';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, '../src/migrations/postgres/data/indonesia-kabkota-wilayah.generated.ts');

/** All two-digit province codes with regency JSON on emsifa (excludes 92,93,95 — covered by remap from 94). */
const EMSIFA_PROVINCE_KODES = [
  '11', '12', '13', '14', '15', '16', '17', '18', '19', '21',
  '31', '32', '33', '34', '35', '36',
  '51', '52', '53',
  '61', '62', '63', '64', '65',
  '71', '72', '73', '74', '75', '76',
  '81', '82',
  '91',
  '94',
];

/** Old Papua (emsifa 94) → our province kode after pemekaran (SeedProvinces names). */
const PAPUA_PEMEKARAN_KODE_TO_PROVINCE = {
  // 92 Papua Selatan
  '9401': '92',
  '9413': '92',
  '9414': '92',
  '9415': '92',
  // 93 Papua Tengah
  '9404': '93',
  '9410': '93',
  '9411': '93',
  '9412': '93',
  '9433': '93',
  '9434': '93',
  '9435': '93',
  '9436': '93',
  // 94 Papua Pegunungan
  '9402': '94',
  '9416': '94',
  '9417': '94',
  '9418': '94',
  '9429': '94',
  '9430': '94',
  '9431': '94',
  '9432': '94',
  // 95 Papua (induk)
  '9403': '95',
  '9408': '95',
  '9409': '95',
  '9419': '95',
  '9420': '95',
  '9426': '95',
  '9427': '95',
  '9428': '95',
  '9471': '95',
};

/** Stays in 91 Papua Barat (Manokwari dkk.); rest Sorong Raya → 96 Papua Barat Daya. */
const PAPUA_BARAT_DAYA_KODES = new Set(['9106', '9107', '9108', '9109', '9110', '9171']);

function get(url) {
  return new Promise((resolve, reject) => {
    https
      .get(url, (res) => {
        let d = '';
        res.on('data', (c) => (d += c));
        res.on('end', () => {
          try {
            resolve(JSON.parse(d));
          } catch (e) {
            reject(e);
          }
        });
      })
      .on('error', reject);
  });
}

function titleCaseWords(rest) {
  return rest
    .toLowerCase()
    .split(/\s+/)
    .map((w) =>
      w
        .split('-')
        .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
        .join('-'),
    )
    .join(' ');
}

/** Collapse spaced acronyms (S I A K) then title-case after KABUPATEN/KOTA prefix. */
function normalizeApiName(name) {
  let s = name.trim();
  const u = s.toUpperCase();
  let rest = '';
  let prefix = '';
  if (u.startsWith('KABUPATEN ')) {
    prefix = 'Kabupaten ';
    rest = s.slice(10).trim();
  } else if (u.startsWith('KOTA ')) {
    prefix = 'Kota ';
    rest = s.slice(5).trim();
  } else {
    return s;
  }
  rest = rest.replace(/([A-Z])\s+(?=[A-Z](?:\s|$))/g, '$1');
  return prefix + titleCaseWords(rest);
}

(async () => {
  const byKode = new Map();

  for (const pid of EMSIFA_PROVINCE_KODES) {
    const url = `https://raw.githubusercontent.com/emsifa/api-wilayah-indonesia/master/static/api/regencies/${pid}.json`;
    const regs = await get(url);
    for (const r of regs) {
      let provinceKode = String(r.province_id);
      if (pid === '91') {
        provinceKode = PAPUA_BARAT_DAYA_KODES.has(r.id) ? '96' : '91';
      }
      if (pid === '94') {
        provinceKode = PAPUA_PEMEKARAN_KODE_TO_PROVINCE[r.id];
        if (!provinceKode) {
          console.warn('skip unknown old-Papua kode', r.id, r.name);
          continue;
        }
      }
      byKode.set(r.id, {
        kode: r.id,
        nama: normalizeApiName(r.name),
        provinceKode,
      });
    }
  }

  const rows = [...byKode.values()].sort((a, b) => a.kode.localeCompare(b.kode, 'en'));
  const kodes = rows.map((r) => r.kode);

  const body = `/* eslint-disable max-len */
/**
 * AUTO-GENERATED by scripts/generate-indonesia-kabkota-seed.mjs — do not edit by hand.
 * Sources: emsifa/api-wilayah-indonesia static regencies; Papua kab/kota re-parented to
 * provinces 92–96 per pemekaran; Sorong Raya (subset of former 91) assigned to 96 Papua Barat Daya.
 */
export type KabKotaSeedRow = { kode: string; nama: string; provinceKode: string };

export const INDONESIA_KABKOTA_WILAYAH: KabKotaSeedRow[] = ${JSON.stringify(rows, null, 2)};

/** All kab/kota kodes in this seed — for migration down(). */
export const INDONESIA_KABKOTA_WILAYAH_KODES: string[] = ${JSON.stringify(kodes)};
`;

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, body, 'utf8');
  console.log('Wrote', OUT, 'rows', rows.length);
})();
